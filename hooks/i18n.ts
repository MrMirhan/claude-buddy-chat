const TABLES: Record<Lang, Record<Key, string>> = { en, tr }

export type Vars = Record<string, string | number>

export function translate(lang: Lang, key: Key, vars?: Vars): string {
  const text = TABLES[lang][key] ?? en[key]
  return vars ? text.replace(/\{(\w+)\}/g, (all, name: string) => (name in vars ? String(vars[name]) : all)) : text
}

export const isLang = (value: unknown): value is Lang => value === 'en' || value === 'tr'

export const isKey = (value: unknown): value is Key => typeof value === 'string' && value in en
